#!/usr/bin/env python3
"""Generate the contract flag-code vocabulary and Iced byte table.

`asset-catalog.json` owns the 258 `flag.<iso>` / `source` records. Surfaces
must not keep a second inventory, index, or geometry: this generator is the
only writer of both Rust adapters, and the structure gate pins them fresh.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
CATALOG = ROOT / "crates/infiltrator-shared/assets/asset-catalog.json"
CONTRACT_OUTPUT = ROOT / "crates/infiltrator-contract/src/flag_codes_generated.rs"
OUTPUT = ROOT / "crates/infiltrator-iced/src/flag_assets_generated.rs"

CONTRACT_HEADER = """// Generated by scripts/generate_flag_assets.py from
// crates/infiltrator-shared/assets/asset-catalog.json. Do not edit: the
// catalog owns the one rectangular 4:3 flag inventory, and the structure
// gate fails these files open when the catalog and its adapters drift.
//
// `flag.<code>` is the only flag-code vocabulary. Named GeoRegion variants
// are localized aliases; every catalogued code remains a typed NodeRegion.

/// Uppercase two-letter codes for every rectangular flag asset.
#[rustfmt::skip]
pub const FLAG_CODES: &[&str] = &[
"""

CONTRACT_FOOTER = """];

/// Resolve an uppercase node-name token only when a catalogued flag exists.
pub fn flag_code_from_catalog(code: &str) -> Option<&'static str> {
    FLAG_CODES
        .iter()
        .copied()
        .find(|candidate| *candidate == code)
}

/// Whether an uppercase two-letter token has a rectangular flag asset.
pub fn is_flag_code(code: &str) -> bool {
    flag_code_from_catalog(code).is_some()
}
"""

HEADER = """// Generated by scripts/generate_flag_assets.py from
// crates/infiltrator-shared/assets/asset-catalog.json. Do not edit: the
// catalog owns the one rectangular 4:3 flag inventory, and the structure
// gate fails this file open when the two drift.
//
// Every entry is full-bleed square-corner artwork. An uppercase ISO code maps
// to exactly one asset; a missing code means the surface draws a square code
// plate, never a Unicode emoji glyph whose shape depends on the host font.

pub fn flag_svg(code: &str) -> Option<&'static [u8]> {
    Some(match code.to_ascii_uppercase().as_str() {
"""

FOOTER = """        _ => return None,
    })
}

#[rustfmt::skip]
pub const FLAG_CODES: &[&str] = &[
"""


def codes() -> list[str]:
    document = json.loads(CATALOG.read_text(encoding="utf-8"))
    records = [
        record
        for record in document["assets"]
        if record["id"].startswith("flag.")
        and record["format"] == "svg"
        and record["variant"] == "source"
    ]
    result = []
    for record in records:
        match = re.fullmatch(r"flag\.([a-z]{2})", record["id"])
        if match is None:
            raise ValueError(f"invalid flag id: {record['id']}")
        if record["path"] != f"flags/{match.group(1)}.svg":
            raise ValueError(f"flag path does not follow its id: {record['id']}")
        result.append(match.group(1).upper())
    if result != sorted(set(result)):
        raise ValueError("flag codes must be unique and in catalog order")
    return result


def render_contract(items: list[str]) -> str:
    lines = [CONTRACT_HEADER]
    lines.extend(f'    "{code}",\n' for code in items)
    lines.append(CONTRACT_FOOTER)
    return "".join(lines)


def render(items: list[str]) -> str:
    lines = [HEADER]
    lines.extend(
        f'        "{code}" => include_bytes!("../../infiltrator-shared/assets/flags/{code.lower()}.svg"),\n'
        for code in items
    )
    lines.append(FOOTER)
    lines.extend(f'    "{code}",\n' for code in items)
    lines.append("];\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    items = codes()
    expected = {
        CONTRACT_OUTPUT: render_contract(items),
        OUTPUT: render(items),
    }
    if args.check:
        stale = [
            path
            for path, expected_text in expected.items()
            if (path.read_text(encoding="utf-8") if path.is_file() else "") != expected_text
        ]
        if stale:
            for path in stale:
                print(f"{path.relative_to(ROOT)} is stale; run scripts/generate_flag_assets.py")
            return 1
        print(f"flag adapters are fresh ({len(items)} flags)")
        return 0
    for path, expected_text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected_text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(items)} flags)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
