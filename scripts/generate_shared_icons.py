#!/usr/bin/env python3
"""Generate canonical icon files for non-SVG renderers from one vector source.

Slint consumes the canonical Lucide SVGs directly. Android consumes generated
Compose ImageVector path data. Both are derived from the same shared SVG files
registered in the contract's icon authority; no second icon family is added.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
AUTHORITY = ROOT / "crates/infiltrator-contract/assets/design-authority.json"
CANONICAL = ROOT / "crates/infiltrator-shared/assets/ui/iced/svg"
ANDROID_ICONS = ROOT / "android/app/src/main/java/com/musicfrog/infiltrator/ui/common/CanonicalIcons.kt"

PATH_RE = re.compile(r'\bd="([^"]+)"')
RECT_RE = re.compile(r'<rect\b([^>]*)/>')
CIRCLE_RE = re.compile(r'<circle\b([^>]*)/>')
ATTR_RE = re.compile(r'(\w+)="([^"]+)"')


def path_data(svg: str) -> str:
    """Compose's path parser understands the compact SVG path subset used here.

    Canonical rect-only drawings (layout-grid, square) are converted to path
    commands here; that is a representation change, not a new icon source.
    """
    parts = PATH_RE.findall(svg)
    for attributes in RECT_RE.findall(svg):
        values = dict(ATTR_RE.findall(attributes))
        x = float(values.get("x", "0"))
        y = float(values.get("y", "0"))
        width = float(values["width"])
        height = float(values["height"])
        radius = float(values.get("rx", "0"))
        if radius == 0:
            parts.append(f"M{x:g} {y:g}h{width:g}v{height:g}h-{width:g}z")
        else:
            right = x + width
            bottom = y + height
            parts.append(
                f"M{x + radius:g} {y:g}"
                f"H{right - radius:g}"
                f"Q{right:g} {y:g} {right:g} {y + radius:g}"
                f"V{bottom - radius:g}"
                f"Q{right:g} {bottom:g} {right - radius:g} {bottom:g}"
                f"H{x + radius:g}"
                f"Q{x:g} {bottom:g} {x:g} {bottom - radius:g}"
                f"V{y + radius:g}"
                f"Q{x:g} {y:g} {x + radius:g} {y:g}z"
            )
    for attributes in CIRCLE_RE.findall(svg):
        values = dict(ATTR_RE.findall(attributes))
        cx = float(values["cx"])
        cy = float(values["cy"])
        radius = float(values["r"])
        parts.append(
            f"M{cx - radius:g} {cy:g}"
            f"a{radius:g} {radius:g} 0 1 0 {radius * 2:g} 0"
            f"a{radius:g} {radius:g} 0 1 0 -{radius * 2:g} 0z"
        )
    return "\n        ".join(parts)


def generated_kotlin(authority: dict) -> str:
    names = sorted({icon["canonical_name"] for icon in authority["icons"]})
    lines = [
        "package com.musicfrog.infiltrator.ui.common",
        "",
        "// Generated by scripts/generate_shared_icons.py from the canonical shared SVG sources.",
        "// Business code resolves semantic ids; this generated owner holds the one path set.",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.PathParser",
        "import androidx.compose.ui.unit.dp",
        "",
        "object CanonicalIcons {",
        "    private fun vector(pathData: String): ImageVector = ImageVector.Builder(",
        "        defaultWidth = 24.dp,",
        "        defaultHeight = 24.dp,",
        "        viewportWidth = 24f,",
        "        viewportHeight = 24f,",
        "    ).apply {",
        "        addPath(PathParser().parsePathString(pathData).toNodes())",
        "    }.build()",
        "",
    ]
    for name in names:
        source = CANONICAL / f"{name}.svg"
        if not source.is_file():
            raise SystemExit(f"missing canonical SVG: {source}")
        data = path_data(source.read_text(encoding="utf-8"))
        if not data:
            raise SystemExit(f"canonical SVG has no path data: {source}")
        key = re.sub(r"[^A-Za-z0-9]", "_", name).upper()
        lines += [
            f"    val {key}: ImageVector by lazy {{ vector(\"\"\"",
            f"        {data}",
            "    \"\"\".trimIndent()) }",
            "",
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    authority = json.loads(AUTHORITY.read_text(encoding="utf-8"))
    expected = generated_kotlin(authority)
    if args.check:
        if not ANDROID_ICONS.is_file() or ANDROID_ICONS.read_text(encoding="utf-8") != expected:
            print("stale generated file: android CanonicalIcons.kt", file=sys.stderr)
            return 1
        return 0
    ANDROID_ICONS.parent.mkdir(parents=True, exist_ok=True)
    ANDROID_ICONS.write_text(expected, encoding="utf-8")
    print("generated canonical Android icon owner")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
