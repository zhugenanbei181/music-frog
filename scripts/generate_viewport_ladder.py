#!/usr/bin/env python3
"""Generate the Slint viewport ladder from the exported contract table.

The shared contract owns the answer to "which viewport tier is this window?".
It exports that answer in `page-structure.json`, the same document the
space-utilization judge reads. This script is the only writer of the Slint
adapter, so a surface cannot keep a private ladder of its own: the structure
gate re-runs this script with `--check` and a hand edit fails as stale.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
EXPORT = ROOT / "crates/infiltrator-contract/assets/page-structure.json"
OUTPUT = ROOT / "crates/infiltrator-slint/ui/components/viewport-ladder.slint"

HEADER = """// Generated by scripts/generate_viewport_ladder.py from
// crates/infiltrator-contract/assets/page-structure.json. Do not edit: the
// shared contract's `responsive_viewport` owns the ladder, and the structure
// gate fails this file open when the two drift.
//
// Every boundary, navigation column and column count below is the exported
// projection of one `ViewportTier`. A surface that writes its own boundary
// would be a second idea of the same window - the defect this file exists to
// make impossible. Lengths are design units, so the consumer applies the
// user zoom itself and the ladder never has an opinion about it.

import { LumenUiScale } from "../lumen-ui-scale.slint";
import { DashboardDensity, NavigationForm, NavigationSeparator, SidebarExpansionPreference, ViewportTier } from "./viewport_tier.slint";

export global ViewportLadder {
"""

BOUNDARY_DOC = [
    "The first window width that leaves each tier behind, in design units.",
    "The half-open spans tile the width axis: `compact` < `medium` <",
    "`expanded` < `ultra`, and the widest tier owns no upper bound, so the",
    "chain that reads these ends in `ultra` without a fourth number.",
]

NODE_COLUMNS_DOC = [
    "Node cards per row on the proxy page. This is the count the Iced and",
    "Bevy shells use at the same width, so one window never gets four",
    "columns on one surface and three on another.",
    "",
    "The dashboard's own column count is a DIFFERENT typed fact, not this",
    "lookup: see `dashboard_grid_shares` below.",
]

DASHBOARD_DOC = [
    "How many equal shares the dashboard's span grid owns at this page width.",
    "",
    "The contract's `DashboardColumns::GridShares` answers this by page width",
    "(FlClash `dashboardColumnsOf`: below 860 -> 2, at or above -> 4), while",
    "`overview_card_columns` answers a different question - cards per row in a",
    "wrapping flow (1/2/2/3 by tier). SPACEUTIL-008 existed because Slint's",
    "private 2/4 and the contract's 1/2/2/3 were both called `card columns`.",
    "A rail-form window is held to two shares regardless of width: its grid",
    "is the compact `DashboardDensity` and a four-share row there clipped the",
    "last card off the right edge (measured at 720px). That is a typed form",
    "switch, not a second width rule. This lookup is generated from the",
    "exported threshold, so neither the surface nor this generator owns a",
    "second copy of the number.",
]

DENSITY_DOC = [
    "The typed dashboard density for the page body's own room.",
    "",
    "FlClash resolves `DashboardDensity.of(size)` inside the scaffold's",
    "LayoutBuilder, then injects it through a scope so every card asks one",
    "fact instead of measuring the window. The exported thresholds below",
    "are that decision projected into Slint design units: a page narrower",
    "than 640 is mobile, a four-share page narrower than 1040 is compact,",
    "and a desktop page shorter than 824 is compact. `is_compact` is the",
    "only derived answer the dashboard grid consumes.",
]

SIDEBAR_VARIANT_DOC = [
    "FlClash persists only `sidebarExpanded` in app settings and derives one",
    "`expanded` fact from the viewport capability. The contract exports the",
    "closed preference x tier x surface-kind table below; this generated",
    "lookup only spells its typed answer in the surface vocabulary. A user",
    "who collapses a desktop window therefore gets the existing rail form,",
    "and a touch surface keeps its bottom bar without a second UI decision.",
]

SEPARATOR_DOC = [
    "Whether a navigation form may paint a group heading.",
    "",
    "FlClash's desktop scene and prism_ui sidebar both publish one",
    "uninterrupted destination list. A heading spends its own line box and",
    "the air above it, so it splits one navigation stack into two. The",
    "exported contract decides the separator; this generated lookup only",
    "projects that decision into the surface vocabulary.",
]


def form_variant(name: str) -> str:
    """An exported `SidebarForm` id spelled as a Slint enum variant."""
    return f"NavigationForm.{name.replace('_', '-')}"


def separator_variant(name: str) -> str:
    """An exported `NavigationSeparator` id spelled as a Slint variant."""
    return f"NavigationSeparator.{name.replace('_', '-')}"


def boundary_properties(tiers: list[dict]) -> list[str]:
    """The tier exits as scaled lengths, so a binding can compare the width."""
    lines: list[str] = []
    previous: dict | None = None
    for entry in tiers:
        if previous is not None:
            lines.append(
                f"    out property <length> {previous['id']}-max: "
                f"{entry['min_width_px']} * LumenUiScale.unit;"
            )
        previous = entry
    return lines


def tier_function(
    name: str, result: str, doc: list[str], tiers: list[dict], value
) -> list[str]:
    """One exported lookup table over the tier enum."""
    lines = [f"    // {line}".rstrip() for line in doc]
    lines.append(f"    public pure function {name}(tier: ViewportTier) -> {result} {{")
    for entry in tiers[:-1]:
        lines.append(f"        if (tier == ViewportTier.{entry['id']}) {{ return {value(entry)}; }}")
    lines.append(f"        return {value(tiers[-1])};")
    lines.append("    }")
    lines.append("")
    return lines


def separator_function(document: dict) -> list[str]:
    """One exported lookup table over the navigation form enum."""
    by_form = {
        entry["id"]: entry["separator"]
        for entry in document["navigation_separators"]["forms"]
    }
    lines = [f"    // {line}".rstrip() for line in SEPARATOR_DOC]
    lines.append(
        "    public pure function navigation_separator("
        "form: NavigationForm) -> NavigationSeparator {"
    )
    for form in ("bottom_nav", "rail", "standard", "wide"):
        lines.append(
            f"        if (form == {form_variant(form)}) "
            f"{{ return {separator_variant(by_form[form])}; }}"
        )
    lines.append(f"        return {separator_variant(by_form['wide'])};")
    lines.append("    }")
    lines.append("")
    return lines


def preference_variant(name: str) -> str:
    """An exported `SidebarExpansionPreference` id as a Slint enum variant."""
    return f"SidebarExpansionPreference.{name.replace('_', '-')}"


def sidebar_variant_function(name: str, result: str, variants: list[dict], value) -> list[str]:
    """One exported lookup over the closed preference x tier x surface table."""
    lines = [f"    // {line}".rstrip() for line in SIDEBAR_VARIANT_DOC]
    lines.append(
        "    public pure function "
        f"{name}(preference: SidebarExpansionPreference, tier: ViewportTier, "
        f"touch-surface: bool) -> {result} {{"
    )
    for entry in variants:
        touch = "true" if entry["touch_surface"] else "false"
        lines.append(
            f"        if (preference == {preference_variant(entry['preference'])} "
            f"&& tier == ViewportTier.{entry['tier']} && touch-surface == {touch}) "
            f"{{ return {value(entry)}; }}"
        )
    fallback = variants[-1]
    lines.append(f"        return {value(fallback)};")
    lines.append("    }")
    lines.append("")
    return lines


def slint_ladder(document: dict) -> str:
    tiers = document["tiers"]
    variants = document["sidebar_variants"]
    threshold = int(document["dashboard_columns"]["four_column_min_px"])
    density = document["dashboard_density"]
    desktop_min = int(density["desktop_min_px"])
    standard_four_column_min = int(density["standard_four_column_min_px"])
    standard_height_min = int(density["standard_height_min_px"])
    body: list[str] = [f"    // {line}".rstrip() for line in BOUNDARY_DOC]
    body += boundary_properties(tiers)
    body.append("")
    body += separator_function(document)
    body += sidebar_variant_function(
        "sidebar_form",
        "NavigationForm",
        variants,
        lambda entry: form_variant(entry["nav_form"]),
    )
    body += sidebar_variant_function(
        "sidebar_nav_column",
        "int",
        variants,
        lambda entry: str(entry["nav_column_px"]),
    )
    body += sidebar_variant_function(
        "sidebar_labelled",
        "bool",
        variants,
        lambda entry: "true" if entry["labelled_sidebar"] else "false",
    )
    body += sidebar_variant_function(
        "sidebar_toggle_available",
        "bool",
        variants,
        lambda entry: "true" if entry["toggle_available"] else "false",
    )
    body += tier_function(
        "proxy_node_columns",
        "int",
        NODE_COLUMNS_DOC,
        tiers,
        lambda entry: str(entry["proxy_node_columns"]),
    )
    body += [f"    // {line}".rstrip() for line in DASHBOARD_DOC]
    body.append(
        "    public pure function dashboard_grid_shares("
        "page-width: length, tier: ViewportTier) -> int {"
    )
    body.append(
        "        if (tier == ViewportTier.compact || tier == ViewportTier.medium) "
        "{ return 2; }"
    )
    body.append(
        f"        if (page-width < {threshold} * LumenUiScale.unit) {{ return 2; }}"
    )
    body.append("        return 4;")
    body.append("    }")
    body.append("")
    body += [f"    // {line}".rstrip() for line in DENSITY_DOC]
    body.append(
        "    public pure function dashboard_density("
        "page-width: length, page-height: length) -> DashboardDensity {"
    )
    body.append(
        f"        if (page-width < {desktop_min} * LumenUiScale.unit) "
        "{ return DashboardDensity.mobile; }"
    )
    body.append(
        "        if ((page-width >= "
        f"{threshold} * LumenUiScale.unit && page-width < "
        f"{standard_four_column_min} * LumenUiScale.unit) || "
        f"page-height < {standard_height_min} * LumenUiScale.unit) "
        "{ return DashboardDensity.compact; }"
    )
    body.append("        return DashboardDensity.standard;")
    body.append("    }")
    body.append("")
    body.append(
        "    public pure function dashboard_is_compact("
        "density: DashboardDensity) -> bool {"
    )
    body.append(
        "        return density == DashboardDensity.compact;"
    )
    body.append("    }")
    body.append("")
    return HEADER + "\n".join(body).rstrip() + "\n}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="verify the generated ladder without writing it"
    )
    args = parser.parse_args()
    if not EXPORT.is_file():
        print(f"viewport ladder export is missing: {EXPORT.relative_to(ROOT)}", file=sys.stderr)
        return 1
    document = json.loads(EXPORT.read_text(encoding="utf-8"))
    if document.get("version") != 11:
        print(
            "page-structure.json is not the ladder-bearing version 11 export; "
            "rerun export_page_structure",
            file=sys.stderr,
        )
        return 1
    content = slint_ladder(document)
    if args.check:
        if not OUTPUT.is_file():
            print(f"missing generated file: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != content:
            print(f"stale generated file: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"viewport ladder adapter is fresh: {OUTPUT.relative_to(ROOT)}")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
